# Note: TURBERCULOSIS is the intentional spelling preserved from model configuration
DEFAULT_CLASS_MAPPING: Dict[int, str] = {
    0: "COVID19",
    1: "NORMAL",
    2: "PNEUMONIA",
    3: "TURBERCULOSIS",
}

DEFAULT_DISPLAY_NAMES: Dict[str, str] = {
    "COVID19": "COVID-19",
    "NORMAL": "Normal",
    "PNEUMONIA": "Pneumonia",
    "TURBERCULOSIS": "Tuberculosis",
}


# ==============================================================================
# Domain Exceptions
# ==============================================================================


class InferenceError(Exception):
    """Base exception for all inference and prediction failures."""

    def __init__(
        self,
        message: str,
        error_code: str = "INFERENCE_ERROR",
        details: Optional[Dict[str, Any]] = None,
    ) -> None:
        super().__init__(message)
        self.message = message
        self.error_code = error_code
        self.details = details or {}


class ModelUnavailableError(InferenceError):
    """Raised when the pre-trained DenseNet121 model is not loaded or inaccessible."""

    def __init__(
        self,
        message: str = "DenseNet121 model is not loaded or unavailable for inference.",
        details: Optional[Dict[str, Any]] = None,
    ) -> None:
        super().__init__(message=message, error_code="MODEL_UNAVAILABLE", details=details)


class InvalidModelOutputError(InferenceError):
    """Raised when model output violates shape, finiteness, range, or sum contracts."""

    def __init__(
        self,
        message: str,
        details: Optional[Dict[str, Any]] = None,
    ) -> None:
        super().__init__(message=message, error_code="INVALID_MODEL_OUTPUT", details=details)


class InferenceExecutionError(InferenceError):
    """Raised when the forward inference pass fails during neural network execution."""

    def __init__(
        self,
        message: str,
        details: Optional[Dict[str, Any]] = None,
    ) -> None:
        super().__init__(message=message, error_code="INFERENCE_EXECUTION_ERROR", details=details)


# ==============================================================================
# Structured Result Contracts
# ==============================================================================


@dataclass(frozen=True)
class PredictionResult:
    """Immutable structured result returned by the four-class inference service."""

    predicted_class: str
    predicted_label: str
    confidence: float
    probabilities: Dict[str, float]
    model_name: str
    model_architecture: str
    input_width: int
    input_height: int
    processed_width: int
    processed_height: int
    inference_time_ms: float
    preprocessing_time_ms: float
    disclaimer: str = RESEARCH_DISCLAIMER

    def to_dict(self) -> Dict[str, Any]:
        """Return a JSON-serializable dictionary representation of the prediction result."""
        return {
            "predicted_class": self.predicted_class,
            "predicted_label": self.predicted_label,
            "confidence": self.confidence,
            "probabilities": self.probabilities,
            "model_name": self.model_name,
            "model_architecture": self.model_architecture,
            "input_width": self.input_width,
            "input_height": self.input_height,
            "processed_width": self.processed_width,
            "processed_height": self.processed_height,
            "inference_time_ms": self.inference_time_ms,
            "preprocessing_time_ms": self.preprocessing_time_ms,
            "disclaimer": self.disclaimer,
        }

    def to_response(self) -> Any:
        """Convert to Pydantic PredictionResponse schema if pydantic is available in runtime."""
        try:
            from app.core.request_context import get_request_id
            from app.schemas.prediction import PredictionResponse

            d = self.to_dict()
            d["status"] = "success"
            d["display_name"] = self.predicted_label
            req_id = get_request_id()
            if req_id and req_id != "-":
                d["request_id"] = req_id
            return PredictionResponse(**d)
        except Exception:
            return self.to_dict()


# ==============================================================================
# Inference Service Implementation
# ==============================================================================


class InferenceService:
    """Production-grade Chest X-ray DenseNet121 Inference Service."""

    def __init__(
        self,
        model_loader: Optional[ModelLoader] = None,
        preprocessor: Optional[ImagePreprocessor] = None,
        coordinator: Optional[Any] = None,
    ) -> None:
        """Initialize the inference service with dependency injection support.

        Args:
            model_loader: Optional ModelLoader instance (defaults to application singleton).
            preprocessor: Optional ImagePreprocessor instance (defaults to application singleton).
            coordinator: Optional MLExecutionCoordinator instance (defaults to application singleton).
        """
        self._model_loader = model_loader or get_model_loader()
        self._preprocessor = preprocessor or get_image_preprocessor()
        if coordinator is not None:
            self._coordinator = coordinator
        else:
            from app.services.ml_coordinator import get_ml_coordinator
            self._coordinator = get_ml_coordinator()

    @property
    def coordinator(self) -> Any:
        """Return the associated MLExecutionCoordinator instance."""
        return self._coordinator

    def predict(self, image_bytes: bytes) -> PredictionResult:
        """Execute end-to-end chest X-ray image validation, preprocessing, and model inference.

        Args:
            image_bytes: Raw binary image payload.

        Returns:
            PredictionResult containing the predicted class, confidence, softmax probabilities,
            and operational latency telemetry.

        Raises:
            EmptyImageError: If byte sequence is empty.
            ImageTooLargeError: If bytes exceed max upload size.
            UnsupportedFormatError: If image format is not JPEG, PNG, or WEBP.
            CorruptImageError: If image cannot be identified or decoded.
            DecompressionBombError: If image exceeds maximum pixel limits.
            ModelUnavailableError: If the model cannot be loaded into memory.
            InferenceExecutionError: If the forward computation fails.
            InvalidModelOutputError: If model output violates numerical contracts.
        """
        # Step 1: Preprocess raw image bytes with high-resolution timing
        t_prep_start = time.perf_counter()
        preprocessed = self._preprocessor.preprocess(image_bytes)
        t_prep_end = time.perf_counter()
        preprocessing_time_ms = (t_prep_end - t_prep_start) * 1000.0

        # Step 2: Forward pass through preprocessed tensor
        return self.predict_tensor(
            tensor=preprocessed.tensor,
            original_width=preprocessed.original_width,
            original_height=preprocessed.original_height,
            preprocessing_time_ms=preprocessing_time_ms,
        )

    def predict_tensor(
        self,
        tensor: np.ndarray,
        original_width: int = 224,
        original_height: int = 224,
        preprocessing_time_ms: float = 0.0,
    ) -> PredictionResult:
        """Execute model inference directly on an already preprocessed tensor.

        Args:
            tensor: Preprocessed tensor of shape (1, 224, 224, 3) and dtype float32.
            original_width: Original image width before resizing.
            original_height: Original image height before resizing.
            preprocessing_time_ms: Elapsed preprocessing duration in milliseconds.

        Returns:
            PredictionResult with classification outputs and telemetry.
        """
        # Step 1: Obtain pre-loaded model instance (avoid reloading per request)
        model = self._get_model_instance()

        # Step 2: Retrieve configured class and display mappings
        class_mapping, display_names = self._get_class_mappings()

        # Step 3: Execute model forward pass under shared coordinator execution lock
        # Architectural rationale:
        # - model(..., training=False) directly executes the Keras computational graph,
        #   bypassing the dataset iterator, progress bar, and batching overhead of model.predict().
        # - The shared coordinator lock protects against state collisions in TensorFlow eager
        #   execution across concurrent inference and Grad-CAM requests.
        # - Serialized execution means CPU inference latency is approximately 35-65 ms per call.
        from app.services.ml_coordinator import MLNotReadyError

        try:
            with self._coordinator.acquire_execution():
                t_infer_start = time.perf_counter()
                try:
                    raw_output = model(tensor, training=False)
                    if hasattr(raw_output, "numpy"):
                        output_array = raw_output.numpy()
                    else:
                        output_array = np.asarray(raw_output)
                except Exception as exc:
                    logger.exception("DenseNet121 model forward pass execution failed: %s", exc)
                    raise InferenceExecutionError(
                        f"Model forward pass execution failed: {exc}",
                        details={"error": str(exc)},
                    ) from exc
                t_infer_end = time.perf_counter()
                inference_time_ms = (t_infer_end - t_infer_start) * 1000.0
        except MLNotReadyError as exc:
            logger.warning("Model execution rejected by coordinator: %s", exc)
            raise ModelUnavailableError(
                str(exc),
                details={"lifecycle_state": exc.state.value},
            ) from exc

        # Step 4: Defensive validation of output tensor contracts
        self._validate_output_tensor(output_array)

        # Step 5: Map output probabilities to research classes
        probabilities: Dict[str, float] = {}
        for i in range(4):
            class_key = class_mapping.get(i, DEFAULT_CLASS_MAPPING.get(i, f"CLASS_{i}"))
            probabilities[class_key] = float(output_array[0, i])

        predicted_idx = int(np.argmax(output_array[0]))
        predicted_class = class_mapping.get(
            predicted_idx, DEFAULT_CLASS_MAPPING.get(predicted_idx, f"CLASS_{predicted_idx}")
        )
        predicted_label = display_names.get(predicted_class, predicted_class)
        confidence = float(output_array[0, predicted_idx])

        # Step 6: Extract architectural metadata
        model_name = "LungCare DenseNet121"
        model_architecture = "DenseNet121"
        if getattr(self._model_loader, "metadata", None):
            model_name = self._model_loader.metadata.model_name
        elif hasattr(model, "name") and model.name:
            model_name = str(model.name)

        logger.info(
            "Inference successful: predicted=%s (%s), confidence=%.4f, infer_time=%.2fms, prep_time=%.2fms",
            predicted_class,
            predicted_label,
            confidence,
            inference_time_ms,
            preprocessing_time_ms,
        )

        return PredictionResult(
            predicted_class=predicted_class,
            predicted_label=predicted_label,
            confidence=confidence,
            probabilities=probabilities,
            model_name=model_name,
            model_architecture=model_architecture,
            input_width=original_width,
            input_height=original_height,
            processed_width=224,
            processed_height=224,
            inference_time_ms=inference_time_ms,
            preprocessing_time_ms=preprocessing_time_ms,
            disclaimer=RESEARCH_DISCLAIMER,
        )

    # --------------------------------------------------------------------------
    # Internal Helpers & Contract Validation
    # --------------------------------------------------------------------------

    def _get_model_instance(self) -> Any:
        """Retrieve the validated model instance, verifying model availability."""
        try:
            model = self._model_loader.get_model()
        except Exception as exc:
            logger.exception("Failed to retrieve DenseNet121 model instance: %s", exc)
            raise ModelUnavailableError(
                f"DenseNet121 model is unavailable: {exc}",
                details={"error": str(exc)},
            ) from exc

        if model is None:
            raise ModelUnavailableError(
                "DenseNet121 model instance is None. Model is not ready for inference.",
                details={"is_loaded": getattr(self._model_loader, "is_loaded", False)},
            )

        # Synchronize coordinator state if loader is loaded (e.g. mock loaders or direct initialization)
        from app.services.ml_coordinator import ModelLifecycleState
        if getattr(self._model_loader, "is_loaded", False) and self._coordinator.state != ModelLifecycleState.DRAINING:
            if not self._coordinator.is_ready:
                self._coordinator.complete_loading()

        return model

    def _get_class_mappings(self) -> Tuple[Dict[int, str], Dict[str, str]]:
        """Retrieve class index mappings and display names from artifacts or defaults."""
        class_mapping = DEFAULT_CLASS_MAPPING.copy()
        display_names = DEFAULT_DISPLAY_NAMES.copy()

        artifacts = getattr(self._model_loader, "_artifacts", None)
        if artifacts and hasattr(artifacts, "config_data") and isinstance(artifacts.config_data, dict):
            cfg_classes = artifacts.config_data.get("class_mapping")
            if isinstance(cfg_classes, dict):
                try:
                    class_mapping = {int(k): str(v) for k, v in cfg_classes.items()}
                except (ValueError, TypeError):
                    class_mapping = DEFAULT_CLASS_MAPPING.copy()

            cfg_names = artifacts.config_data.get("display_names")
            if isinstance(cfg_names, dict):
                display_names = {str(k): str(v) for k, v in cfg_names.items()}

        return class_mapping, display_names

    def _validate_output_tensor(self, output: np.ndarray) -> None:
        """Validate output tensor shape, finiteness, probability bounds, and sum contracts."""
        if not isinstance(output, np.ndarray):
            raise InvalidModelOutputError(
                f"Model output must be a NumPy array, got '{type(output).__name__}'.",
                details={"output_type": type(output).__name__},
            )

        if output.shape != (1, 4):
            raise InvalidModelOutputError(
                f"Model output shape contract violated: expected (1, 4), got {output.shape}.",
                details={"actual_shape": list(output.shape), "expected_shape": [1, 4]},
            )

        if not np.all(np.isfinite(output)):
            has_nan = bool(np.any(np.isnan(output)))
            has_inf = bool(np.any(np.isinf(output)))
            raise InvalidModelOutputError(
                f"Model output contains non-finite values (NaN: {has_nan}, Inf: {has_inf}).",
                details={"has_nan": has_nan, "has_inf": has_inf},
            )

        # Allow small floating point numerical tolerance (1e-4) around [0.0, 1.0]
        tol = 1e-4
        if np.any(output < -tol) or np.any(output > (1.0 + tol)):
            min_val = float(np.min(output))
            max_val = float(np.max(output))
            raise InvalidModelOutputError(
                f"Model output probabilities outside valid range [0.0, 1.0] (min: {min_val:.6f}, max: {max_val:.6f}).",
                details={"min_value": min_val, "max_value": max_val},
            )

        # Softmax sum contract: sum of probabilities must be approximately 1.0 within 1e-3 tolerance
        prob_sum = float(np.sum(output[0]))
        if not np.isclose(prob_sum, 1.0, atol=1e-3):
            raise InvalidModelOutputError(
                f"Model output probabilities do not sum to 1.0 (sum={prob_sum:.6f}).",
                details={"probability_sum": prob_sum, "tolerance": 1e-3},
            )


# ==============================================================================
# Thread-Safe Singleton Accessor
# ==============================================================================

_inference_service_instance: Optional[InferenceService] = None
_inference_service_lock = threading.Lock()


def get_inference_service(
    model_loader: Optional[ModelLoader] = None,
    preprocessor: Optional[ImagePreprocessor] = None,
) -> InferenceService:
    """Return the application-wide singleton instance of InferenceService.

    Note on concurrency: All callers sharing this singleton instance will share
    its internal forward-pass lock, serializing forward inference calls across threads.
    """
    global _inference_service_instance
    if _inference_service_instance is None or model_loader is not None or preprocessor is not None:
        with _inference_service_lock:
            if _inference_service_instance is None or model_loader is not None or preprocessor is not None:
                _inference_service_instance = InferenceService(
                    model_loader=model_loader,
                    preprocessor=preprocessor,
                )
    return _inference_service_instance
